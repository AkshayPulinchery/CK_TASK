"use client";

import { formatGovDate, type Circular } from "@/lib/portal-data";

/** Browser-side download of a generated text document. */
export function downloadTextFile(filename: string, text: string): void {
  const blob = new Blob([text], { type: "text/plain;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  window.setTimeout(() => URL.revokeObjectURL(url), 2000);
}

/** Plain-text rendering of a circular, used by the download action. */
export function circularToText(circular: Circular): string {
  const line = "=".repeat(66);
  return [
    line,
    "GOVERNMENT OF TAMIL NADU",
    circular.department,
    line,
    "",
    `${circular.kind.toUpperCase()}  ${circular.number}`,
    `Dated: ${formatGovDate(circular.date)}`,
    "",
    circular.title,
    "",
    "-".repeat(66),
    "",
    circular.summary,
    "",
    "-".repeat(66),
    "",
    "This is a demonstration copy generated by the CivicForce TN portal.",
    "Certified copies are issued by the concerned department.",
    "",
    "Public portal: CivicForce TN — Citizen Action Engine",
    "Enquiries: 1100 (state emergency desk) · 1913 (women's helpline)",
    line,
  ].join("\n");
}

export function downloadCircular(circular: Circular): void {
  downloadTextFile(`${circular.number}-${circular.kind.replace(/\s+/g, "-")}.txt`, circularToText(circular));
}
