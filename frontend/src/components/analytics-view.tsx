"use client";

import { useMemo, useState } from "react";
import Link from "next/link";
import { useReports } from "@/components/providers";
import { useI18n } from "@/components/language-provider";
import { categoryKey } from "@/lib/i18n";
import { downloadTextFile } from "@/lib/document-download";
import { Icon } from "@/components/icons";
import { Skeleton } from "@/components/portal/skeleton";

function isResolved(status: string): boolean {
  return status.trim().toLowerCase() === "resolved";
}

function isOpen(status: string): boolean {
  const s = status.trim().toLowerCase();
  return s === "under review" || s === "assigned" || s === "in progress";
}

function countBy<T>(items: T[], key: (item: T) => string): { key: string; count: number }[] {
  const map = new Map<string, number>();
  for (const item of items) {
    const k = key(item);
    map.set(k, (map.get(k) ?? 0) + 1);
  }
  return [...map.entries()]
    .map(([k, count]) => ({ key: k, count }))
    .sort((a, b) => b.count - a.count);
}

export default function AnalyticsView() {
  const { reports, loading } = useReports();
  const { t } = useI18n();
  const [tab, setTab] = useState<"district" | "category" | "department">("district");

  const data = useMemo(() => {
    const total = reports.length;
    const resolved = reports.filter((r) => isResolved(r.status)).length;
    const open = reports.filter((r) => isOpen(r.status)).length;
    const rate = total === 0 ? 0 : Math.round((resolved / total) * 100);

    const districts = countBy(reports, (r) => r.district).map((row) => {
      const rows = reports.filter((r) => r.district === row.key);
      const res = rows.filter((r) => isResolved(r.status)).length;
      return {
        ...row,
        resolved: res,
        rate: rows.length === 0 ? 0 : Math.round((res / rows.length) * 100),
      };
    });

    const categories = countBy(reports, (r) => r.category);
    const departments = countBy(reports, (r) => r.partner ?? "Pending allocation");

    return { total, resolved, open, rate, districts, categories, departments };
  }, [reports]);

  const maxCategory = Math.max(1, ...data.categories.map((c) => c.count));
  const maxDepartment = Math.max(1, ...data.departments.map((d) => d.count));

  const exportCsv = () => {
    const header = "District,Reports,Resolved,Resolution rate (%)\n";
    const rows = data.districts
      .map((d) => `${d.key},${d.count},${d.resolved},${d.rate}`)
      .join("\n");
    downloadTextFile(
      "civicforce-district-performance.csv",
      `${header}${rows}\n\nGenerated by CivicForce TN — live register\n`
    );
  };

  if (loading && reports.length === 0) {
    return (
      <div className="space-y-4" role="status" aria-label="Loading analytics">
        <div className="grid grid-cols-2 gap-3 lg:grid-cols-4">
          {Array.from({ length: 4 }).map((_, i) => (
            <Skeleton key={i} className="h-24 w-full" />
          ))}
        </div>
        <Skeleton className="h-80 w-full" />
        <span className="sr-only">Loading analytics…</span>
      </div>
    );
  }

  const tiles = [
    { label: t("stats.total"), value: data.total, sub: t("stats.totalSub"), icon: "fileText" as const },
    { label: t("stats.resolved"), value: data.resolved, sub: `${data.rate}% ${t("stats.rate")}`, icon: "checkCircle" as const },
    { label: t("stats.inProgress"), value: data.open, sub: t("stats.inProgressSub"), icon: "clock" as const },
    { label: t("stats.departments"), value: data.departments.filter((d) => d.key !== "Pending allocation").length, sub: t("stats.departmentsSub"), icon: "building" as const },
  ];

  return (
    <div className="space-y-4">
      <div className="grid grid-cols-2 gap-3 lg:grid-cols-4">
        {tiles.map((tile) => (
          <div key={tile.label} className="card-gov p-4">
            <div className="flex items-start justify-between gap-2">
              <p className="text-[9.5px] font-extrabold uppercase tracking-[0.12em] text-[var(--gov-muted)]">
                {tile.label}
              </p>
              <Icon name={tile.icon} size={15} className="text-[var(--gov-link)]" />
            </div>
            <p className="mt-1 text-[26px] font-extrabold leading-none tabular-nums text-[var(--gov-heading)]">
              {tile.value}
            </p>
            <p className="mt-1 text-[10px] text-[var(--gov-muted)]">{tile.sub}</p>
          </div>
        ))}
      </div>

      <div className="card-gov overflow-hidden">
        <div className="flex flex-wrap items-center justify-between gap-2 border-b border-[var(--gov-border)] px-4 py-3">
          <div className="flex flex-wrap gap-1.5" role="tablist" aria-label="Analytics breakdown">
            {(
              [
                { id: "district", label: t("district.colDistrict") },
                { id: "category", label: t("ch.allCategories") },
                { id: "department", label: t("stats.departments") },
              ] as const
            ).map((item) => (
              <button
                key={item.id}
                type="button"
                role="tab"
                aria-selected={tab === item.id}
                onClick={() => setTab(item.id)}
                className={`rounded px-2.5 py-1 text-[11px] font-bold transition-colors ${
                  tab === item.id
                    ? "bg-[var(--gov-navy)] text-white"
                    : "bg-[var(--gov-slate)] text-[var(--gov-muted)] hover:text-[var(--gov-heading)]"
                }`}
              >
                {item.label}
              </button>
            ))}
          </div>

          <div className="flex items-center gap-2">
            <span className="hidden items-center gap-1 text-[10px] font-semibold text-[var(--gov-muted)] sm:flex">
              <span className="live-dot" aria-hidden="true" />
              {t("stats.live")}
            </span>
            <button type="button" onClick={exportCsv} className="btn btn-outline btn-sm">
              <Icon name="download" size={12} />
              CSV
            </button>
          </div>
        </div>

        <div className="p-4">
          {tab === "district" && (
            <div className="overflow-x-auto">
              <table className="gov-table">
                <caption className="sr-only">District-wise grievance volume and resolution index</caption>
                <thead>
                  <tr>
                    <th scope="col">{t("district.colDistrict")}</th>
                    <th scope="col" className="text-right">{t("district.colReports")}</th>
                    <th scope="col" className="text-right">{t("district.resolved")}</th>
                    <th scope="col" className="w-[40%]">{t("district.colIndex")}</th>
                  </tr>
                </thead>
                <tbody>
                  {data.districts.map((row) => (
                    <tr key={row.key}>
                      <td className="font-semibold text-[var(--gov-heading)]">{row.key}</td>
                      <td className="text-right tabular-nums">{row.count}</td>
                      <td className="text-right tabular-nums">{row.resolved}</td>
                      <td>
                        <div className="flex items-center gap-2">
                          <div className="h-1.5 flex-1 overflow-hidden rounded-full bg-[var(--gov-slate)]">
                            <div
                              className="h-full rounded-full bg-[var(--gov-emerald)]"
                              style={{ width: `${row.rate}%` }}
                            />
                          </div>
                          <span className="w-9 text-right text-[10.5px] font-bold tabular-nums text-[var(--gov-muted)]">
                            {row.rate}%
                          </span>
                        </div>
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
              {data.districts.length === 0 && (
                <p className="py-8 text-center text-[12px] text-[var(--gov-muted)]">
                  {t("home.recent.empty")}
                </p>
              )}
            </div>
          )}

          {tab === "category" && (
            <ul className="space-y-3">
              {data.categories.map((row) => (
                <li key={row.key}>
                  <div className="mb-1 flex items-center justify-between gap-2">
                    <span className="text-[11.5px] font-bold text-[var(--gov-heading)]">
                      {t(categoryKey(row.key)) || row.key}
                    </span>
                    <span className="text-[10.5px] font-bold tabular-nums text-[var(--gov-muted)]">
                      {row.count}
                    </span>
                  </div>
                  <div className="h-2 overflow-hidden rounded-full bg-[var(--gov-slate)]">
                    <div
                      className="h-full rounded-full bg-[var(--gov-navy)]"
                      style={{ width: `${Math.round((row.count / maxCategory) * 100)}%` }}
                    />
                  </div>
                </li>
              ))}
              {data.categories.length === 0 && (
                <p className="py-8 text-center text-[12px] text-[var(--gov-muted)]">
                  {t("home.recent.empty")}
                </p>
              )}
            </ul>
          )}

          {tab === "department" && (
            <ul className="divide-y divide-[var(--gov-border)]">
              {data.departments.map((row) => (
                <li key={row.key} className="flex items-center gap-3 py-2.5 first:pt-0 last:pb-0">
                  <span className="grid h-7 w-7 shrink-0 place-items-center rounded bg-[var(--gov-slate)] text-[var(--gov-heading)]">
                    <Icon name="building" size={13} />
                  </span>
                  <div className="min-w-0 flex-1">
                    <p className="truncate text-[11.5px] font-bold text-[var(--gov-heading)]">{row.key}</p>
                    <div className="mt-1 h-1.5 overflow-hidden rounded-full bg-[var(--gov-slate)]">
                      <div
                        className="h-full rounded-full bg-[var(--gov-emerald)]"
                        style={{ width: `${Math.round((row.count / maxDepartment) * 100)}%` }}
                      />
                    </div>
                  </div>
                  <span className="text-[11px] font-extrabold tabular-nums text-[var(--gov-muted)]">
                    {row.count}
                  </span>
                </li>
              ))}
              {data.departments.length === 0 && (
                <p className="py-8 text-center text-[12px] text-[var(--gov-muted)]">
                  {t("home.recent.empty")}
                </p>
              )}
            </ul>
          )}

          <p className="mt-3 flex items-start gap-1.5 border-t border-[var(--gov-border)] pt-2.5 text-[10px] leading-relaxed text-[var(--gov-muted)]">
            <Icon name="info" size={11} className="mt-[1px] shrink-0" />
            Figures are computed from the live public register. Districts with no reports in the current
            register are omitted. Maximum bar width is relative to the highest value in each view.
          </p>
        </div>
      </div>

      <div className="flex flex-wrap gap-2">
        <Link href="/map" className="btn btn-outline btn-sm">
          <Icon name="mapPin" size={12} />
          {t("gov.nav.map")}
        </Link>
        <Link href="/challenges" className="btn btn-ghost btn-sm">
          <Icon name="list" size={12} />
          {t("stats.viewAll")}
        </Link>
      </div>
    </div>
  );
}
